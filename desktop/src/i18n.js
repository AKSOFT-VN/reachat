export function translateText(s) {
  if (!s) return s;
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  const core = m[2];
  if (!core || !/[À-ỹđĐ]/.test(core)) return s;                 // không có chữ tiếng Việt -> giữ nguyên
  if (D[core] != null) return m[1] + D[core] + m[3];
  for (const [re, rep] of R) {
    const mm = re.exec(core);
    if (mm) return m[1] + (typeof rep === 'function' ? rep(mm) : core.replace(re, rep)) + m[3];
  }
  // Thông báo lỗi gắn tiền tố "⚠️ " -> dịch phần sau
  if (core.startsWith('⚠️ ')) { const t = translateText(core.slice(3)); if (t !== core.slice(3)) return m[1] + '⚠️ ' + t + m[3]; }
  return s;
}

const skip = (el) => !!el?.closest?.(SKIP) && !el.closest('[data-i18n]');
function translateNode(n) {
  if (n.nodeType === 3) {
    if (skip(n.parentElement)) return;
    const t = translateText(n.data);
    if (t !== n.data) n.data = t;
  } else if (n.nodeType === 1) {
    if (skip(n)) { for (const el of n.querySelectorAll('[data-i18n]')) translateNode(el); return; }   // vùng nội dung: chỉ dịch mảnh đã đánh dấu
    for (const a of ['placeholder', 'title', 'aria-label']) {
      const v = n.getAttribute(a);
      if (v) { const t = translateText(v); if (t !== v) n.setAttribute(a, t); }
    }
    for (const c of n.childNodes) translateNode(c);
  }
}

export function startI18n() {
  if (getLang() !== 'en') return;
  document.documentElement.lang = 'en';
  const run = () => {
    translateNode(document.body);
    new MutationObserver((muts) => {
      for (const m of muts) {
        if (m.type === 'characterData') translateNode(m.target);
        else if (m.type === 'attributes') translateNode(m.target);
        else for (const n of m.addedNodes) translateNode(n);
      }
    }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] });
  };
  if (document.body) run(); else addEventListener('DOMContentLoaded', run);
}
